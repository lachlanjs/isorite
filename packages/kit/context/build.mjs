// Writes src/context.gen.ts from reference.md and recipes/*.html: what Iso is given when it builds an artifact
// (plan-m23 §3.7), as strings the engine can import wherever it runs (a server, or the guide's page).
// node packages/kit/context/build.mjs   (the kit's test fails when this wasn't run after a change)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const here = new URL("./", import.meta.url);
export const ABOUT = {
  dashboard: "a dashboard of one data file: numbers, charts and a table, in markup only",
  compare: "two data files with the same columns, compared: together on one chart, and side by side",
  simulation: "a simulation with parameters, play and reset, drawn on a canvas, with a live chart (a script)",
  explorable: "an explorable explanation: inputs, numbers derived from them, and linked views (a script)",
  viewer: "a 3D model's viewer (glTF, GLB, STL, OBJ), with what it is beside it",
};
export function generated() {
  const recipes = Object.fromEntries(Object.keys(ABOUT).map((name) => [name, { about: ABOUT[name], html: readFileSync(new URL(`recipes/${name}.html`, here), "utf8") }]));
  const extra = readdirSync(new URL("recipes/", here)).filter((f) => !(f.replace(/\.html$/, "") in ABOUT));
  if (extra.length) throw new Error(`recipes without a line in ABOUT: ${extra.join(", ")}`);
  return `// Generated by packages/kit/context/build.mjs from reference.md and recipes/: do not edit.\n` +
    `/** The kit's reference, for Iso building an artifact. */\nexport const REFERENCE: string = ${JSON.stringify(readFileSync(new URL("reference.md", here), "utf8"))};\n` +
    `/** Each recipe: when it's the one, and a complete working artifact to change. */\nexport const RECIPES: Record<string, { about: string; html: string }> = ${JSON.stringify(recipes, null, 1)};\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../src/context.gen.ts", here), generated());
  console.log("packages/kit/src/context.gen.ts written");
}
